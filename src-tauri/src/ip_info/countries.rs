// "United States (US)" for a known code, or the code as it came for one that is not listed.
pub fn with_name(code: &str) -> String {
    let upper = code.to_ascii_uppercase();
    match COUNTRIES.binary_search_by_key(&upper.as_str(), |(listed, _)| listed) {
        Ok(index) => format!("{} ({upper})", COUNTRIES[index].1),
        Err(_) => code.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_codes_get_a_name_and_others_are_left_alone() {
        assert_eq!(with_name("US"), "United States (US)");
        assert_eq!(with_name("au"), "Australia (AU)");
        assert_eq!(with_name("GB"), "United Kingdom (GB)");
        assert_eq!(with_name("ZZ"), "ZZ");
        assert_eq!(with_name(""), "");
    }

    #[test]
    fn the_list_is_sorted_and_every_code_is_two_capital_letters() {
        for pair in COUNTRIES.windows(2) {
            assert!(pair[0].0 < pair[1].0, "{} then {}", pair[0].0, pair[1].0);
        }
        for (code, name) in COUNTRIES {
            assert!(code.len() == 2 && code.chars().all(|c| c.is_ascii_uppercase()));
            assert!(!name.is_empty());
        }
    }
}
